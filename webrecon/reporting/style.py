# Severity filter buttons on the assessment report.
FILTER_JS = """
document.querySelectorAll('.filters button').forEach(function(b){
  b.addEventListener('click',function(){
    var sev=b.getAttribute('data-sev');
    document.querySelectorAll('.filters button').forEach(function(x){x.classList.toggle('on',x===b);});
    document.querySelectorAll('[data-sev]').forEach(function(el){
      if(el.closest('.filters')){return;}
      el.style.display=(sev==='all'||el.getAttribute('data-sev')===sev)?'':'none';
    });
  });
});
"""


